"""Task-bound local consumer adapter; no authentication or external action authority.

The operator supplies each task's record scope and permitted local operations.
Original model output is admitted before generated requests execute. Current source, review,
release, validity and principal state are checked again at execution.
"""

import copy
import json
import uuid

from .context_pilot import ContextError, canonical, digest
from .task_contract import validate_stream


class TaskSession:
    """A task owns one registry/source/grant scenario and one immutable evidence ID.

    Use separate registries/source snapshots for concurrent scenarios. The local
    operator controls these objects; this is not an isolation or identity service.
    No approval decision is generated by this adapter.
    """

    def __init__(self, registry, task_id, workspace, consumer, record_ids,
                 allowed_requests, inspector=None, observation_id=None,
                 target_release=None, epoch=None):
        if not isinstance(record_ids, list) or not record_ids or len(set(record_ids)) != len(record_ids):
            raise ValueError("nonempty unique record scope required")
        self.registry, self.task_id, self.workspace = registry, task_id, workspace
        self.consumer, self.record_ids = consumer, sorted(record_ids)
        self.allowed_requests = list(allowed_requests)
        self.inspector, self.observation_id = inspector, observation_id
        self.target_release = target_release
        self.epoch = epoch or uuid.uuid4().hex
        self.trace, self.allowed_citations = [], []
        self.state = self._state()
        self.evidence_id = digest({"task_id": task_id, "epoch": self.epoch, "state": self.state})

    def _state(self):
        registry = self.registry
        release, manifest = registry._active_manifest(self.workspace)
        records, sources = [], {}
        selected, visiting = set(), set()

        def visit(record_id):
            if record_id in visiting:
                raise ValueError("dependency cycle")
            if record_id in selected:
                return
            if record_id not in manifest:
                raise ValueError("required record absent from current manifest")
            visiting.add(record_id)
            row = registry._row(self.workspace, record_id, manifest[record_id])
            body = registry._record_body(row)
            approval = registry.db.execute(
                "SELECT hash,reviewer FROM approvals WHERE workspace=? AND id=? AND version=?",
                (self.workspace, record_id, manifest[record_id])).fetchone()
            issue = None
            try:
                registry._current(row)
                registry._approval(row)
            except ContextError as exc:
                issue = exc.code
            for item in body["evidence"]:
                try:
                    sources[item["path"]] = {"sha256": registry.source_hash(item["path"])}
                except ContextError as exc:
                    sources[item["path"]] = {"error": exc.code}
            records.append({"id": record_id, "version": body["version"], "content_hash": row["hash"],
                            "review_state": row["review_state"], "revoked": row["revoked"],
                            "approval": dict(approval) if approval else None, "issue": issue,
                            "classification": body["classification"], "valid_from": body["valid_from"],
                            "valid_until": body["valid_until"], "evidence": body["evidence"],
                            "dependencies": body["dependencies"]})
            for dep in body["dependencies"]:
                if manifest.get(dep["id"]) != dep["version"]:
                    raise ValueError("dependency mismatch")
                visit(dep["id"])
            visiting.remove(record_id)
            selected.add(record_id)

        for record_id in self.record_ids:
            visit(record_id)
        actors = {self.consumer} | {actor for actor, _ in self.allowed_requests}
        if self.inspector:
            actors.add(self.inspector)
        principals = {actor: copy.deepcopy(registry.principals.get(actor)) for actor in sorted(actors)}
        access = registry.dispatch(self.consumer, {"operation": "knowledge.get", "workspace": self.workspace,
                                                   "record_ids": self.record_ids})
        # The operator state contains receipts/identity, never retrieved record text.
        observation = ({"ok": True, "bundle_hash": access["context"]["bundle_hash"]}
                       if access.get("ok") else access)
        return {"workspace": self.workspace, "active_release": release["name"], "manifest": manifest,
                "records": sorted(records, key=lambda item: item["id"]), "sources": sources,
                "principals": principals, "current_access": observation}

    def assert_current(self):
        try:
            current = self._state()
        except (ContextError, ValueError) as exc:
            raise ValueError("task evidence no longer current") from exc
        if current != self.state:
            raise ValueError("task evidence no longer current")

    def retrieve(self, record_ids):
        """One actual atomic multirecord get, with no fallback/query repair."""
        if (not isinstance(record_ids, list) or not record_ids or len(set(record_ids)) != len(record_ids)
                or not set(record_ids).issubset(self.record_ids)):
            raise ValueError("retrieval exceeds declared task record scope")
        self.assert_current()
        request = {"operation": "knowledge.get", "workspace": self.workspace, "record_ids": record_ids}
        response = self.registry.dispatch(self.consumer, request)
        self.trace.append({"task_id": self.task_id, "evidence_id": self.evidence_id,
                           "principal": self.consumer, "request": request, "response": response})
        if response.get("ok"):
            for entry in response["context"]["records"]:
                citation = ("record", entry["record"]["id"])
                if citation not in self.allowed_citations:
                    self.allowed_citations.append(citation)
        return response

    def allow_raw_sources(self, paths):
        if not set(paths).issubset(self.state["sources"]):
            raise ValueError("source citation exceeds declared task scope")
        self.allowed_citations.extend(("source", path) for path in paths)

    def contract_scope(self):
        citations = list(self.allowed_citations)
        if self.observation_id:
            citations.append(("observation", self.observation_id))
        return {"task_id": self.task_id, "evidence_id": self.evidence_id,
                "allowed_requests": self.allowed_requests, "allowed_citations": citations}

    def public_evidence(self):
        return copy.deepcopy({"contract": "context.task-evidence.v2", "task_id": self.task_id,
                              "evidence_id": self.evidence_id, "epoch": self.epoch,
                              "record_ids": self.record_ids, "state": self.state,
                              "target_release": self.target_release,
                              "observation_id": self.observation_id,
                              "native_action_permission": "unverified; must be independently checked"})

    def _preflight(self, answer):
        self.assert_current()
        if answer["status"] == "ready" and not self.state["current_access"].get("ok"):
            raise ValueError("ready artifact requires current permitted context")
        for item in answer["requests"]:
            request, operation = item["request"], item["request"].get("operation")
            actor = item["principal"]
            workspace = request.get("record", {}).get("workspace") if operation == "record.submit" else request.get("workspace")
            if workspace != self.workspace:
                raise ValueError("request workspace exceeds task scope")
            fields = {"record.submit": {"operation", "record"},
                      "release.publish": {"operation", "workspace", "name", "manifest"},
                      "knowledge.feedback": {"operation", "workspace", "release", "text"},
                      "knowledge.get": {"operation", "workspace", "record_ids"},
                      "knowledge.health": {"operation", "workspace"}}
            if operation not in fields or set(request) != fields[operation]:
                raise ValueError("invalid operation fields")
            role = {"record.submit": "submitter", "release.publish": "publisher", "knowledge.feedback": "consumer",
                    "knowledge.get": "consumer", "knowledge.health": "reviewer"}[operation]
            self.registry._principal(actor, self.workspace, role)
            if operation == "record.submit":
                body = request["record"]
                self.registry._validate_body(body)
                if any(self.state["sources"].get(e["path"]) != {"sha256": e["sha256"]} for e in body["evidence"]):
                    raise ValueError("proposal evidence exceeds current task sources")
                versions = {r["id"]: r["version"] for r in self.state["records"]}
                if any(versions.get(dep["id"]) != dep["version"] for dep in body["dependencies"]):
                    raise ValueError("proposal dependency exceeds task scope")
                existing = self.registry.db.execute(
                    "SELECT hash FROM records WHERE workspace=? AND id=? AND version=?",
                    (self.workspace, body["id"], body["version"])).fetchone()
                previous = self.registry.db.execute(
                    "SELECT MAX(version) FROM records WHERE workspace=? AND id=?",
                    (self.workspace, body["id"])).fetchone()[0] or 0
                if ((existing and existing["hash"] != digest(body))
                        or (not existing and body["version"] != previous + 1)):
                    raise ValueError("proposal conflicts with current immutable versions")
            elif operation == "release.publish":
                self.registry._manifest(request["manifest"])
                if (request["manifest"] != self.state["manifest"] or request["name"] != self.target_release
                        or any(record["issue"] for record in self.state["records"])):
                    raise ValueError("publication lacks exact current reviewed manifest")
                if set(self.record_ids) != set(self.state["manifest"]):
                    raise ValueError("publication requires complete manifest scope")
                if not isinstance(request["name"], str) or not request["name"].strip() or len(request["name"]) > 100:
                    raise ValueError("invalid release name")
                existing = self.registry.db.execute("SELECT hash FROM releases WHERE workspace=? AND name=?",
                                                    (self.workspace, request["name"])).fetchone()
                if existing and existing["hash"] != digest(request["manifest"]):
                    raise ValueError("publication conflicts with immutable release")
            elif operation == "knowledge.feedback":
                if (request["release"] != self.state["active_release"] or not isinstance(request["text"], str)
                        or not request["text"].strip() or len(request["text"]) > 2000):
                    raise ValueError("feedback must bind current release and bounded text")
            elif operation == "knowledge.get":
                if (not isinstance(request["record_ids"], list) or not request["record_ids"]
                        or not set(request["record_ids"]).issubset(self.record_ids)):
                    raise ValueError("request exceeds declared task records")

    def preflight(self, answer):
        try:
            self._preflight(answer)
        except (ContextError, TypeError, KeyError, AttributeError) as exc:
            raise ValueError("invalid task request: " + str(exc)) from exc

    def _execute(self, answer):
        self.preflight(answer)
        results = []
        for item in answer["requests"]:
            if item["mode"] == "draft_only":
                results.append({"executed": False, "reason": "draft_only", "request": item})
                continue
            self.assert_current()
            response = self.registry.dispatch(item["principal"], item["request"])
            results.append({"executed": True, "request": item, "response": response})
        return {"task_id": self.task_id, "evidence_id": self.evidence_id, "requests": results}


def admit_and_execute(text, sessions):
    """Validate original output and task state before generated requests execute.

    Local dispatcher operations retain their own transactions and current checks;
    this does not claim a distributed transaction across separate task stores.
    Currentness checks themselves record local delivery/denial audit events.
    """
    answers = validate_stream(text, [session.contract_scope() for session in sessions])
    for session, answer in zip(sessions, answers):
        session.preflight(answer)
    return [session._execute(answer) for session, answer in zip(sessions, answers)]
